// Drill-down, multi-node, and the TLS decision.
//
// The drill-down endpoints exist because "which transaction?" had one answer in this
// app: type an RPC into the console. What constrains them is the node: verbosity 2
// costs ~11 MB of hex per block (MEASUREMENTS §6) on a server that services one
// connection at a time, so these routes ask for verbosity 1 and getblockstats, and
// say what they refused to report rather than inventing the missing field.
//
// The fake node deliberately REFUSES verbosity 2, which is what turns "the monitor
// never asks" from an intention into an assertion.
import test from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { withApp } from './helpers/http.js';

// The bootstrap admin's password is generated by boot() and read back off
// app.bootstrap -- no shared secret through process.env (see helpers/http.js).
// Declared per test via client.adminPassword.

test('a block can be inspected by height, and reports header + stats + txids', async () => {
  await withApp({}, async ({ client }) => {
    await client.login('admin');
    const state = await client.get('/api/state?series=none');
    const tip = state.body.tip.height;
    assert.ok(tip > 0, 'the fake node has a chain');

    const r = await client.get(`/api/block?height=${tip}`);
    assert.equal(r.status, 200);
    assert.equal(r.body.ok, true, JSON.stringify(r.body));
    assert.equal(r.body.header.height, tip);
    assert.match(r.body.header.hash, /^[0-9a-f]{64}$/);
    assert.ok(r.body.header.nTx >= 1, 'the block has transactions');
    assert.ok(r.body.stats, 'getblockstats came back (fees without fetching every tx)');
    assert.ok(r.body.stats.totalfee >= 0);
    assert.ok(r.body.txids.length >= 1 && r.body.txids.length <= 50, 'a page of txids, not the whole block');
    assert.equal(r.body.txidsTotal, r.body.header.nTx);
    assert.ok(r.body.notes.some((n) => /verbosity=2/.test(n)), 'the route says why it stopped at verbosity 1');
  });
});

test('a block can be inspected by hash, and a bad input is refused with a reason', async () => {
  await withApp({}, async ({ client }) => {
    await client.login('admin');
    const tip = (await client.get('/api/state?series=none')).body.tip.height;
    const byHeight = await client.get(`/api/block?height=${tip}`);
    const hash = byHeight.body.header.hash;

    const byHash = await client.get(`/api/block?hash=${hash}`);
    assert.equal(byHash.body.ok, true);
    assert.equal(byHash.body.header.hash, hash, 'the same block by the other route');

    const badHash = await client.get('/api/block?hash=zzz');
    assert.equal(badHash.status, 400, 'a malformed hash is our error, not the node\'s');
    assert.match(badHash.body.error.message, /64-hex/);

    const badHeight = await client.get('/api/block?height=-4');
    assert.equal(badHeight.status, 400);

    const noBlock = await client.get(`/api/block?hash=${'00'.repeat(32)}`);
    assert.equal(noBlock.status, 200, 'the node\'s own "not found" is data, so it is passed through at 200');
    assert.equal(noBlock.body.ok, false);
    assert.match(noBlock.body.error.message, /not found/i);
  });
});

