test('a transaction decodes, and the fee it cannot have is named rather than guessed', async () => {
  await withApp({}, async ({ client }) => {
    await client.login('admin');
    // Reached through a block rather than the pool: the fake's pool entries churn
    // every tick, and a confirmed txid is stable long enough to assert against.
    const tip = (await client.get('/api/state?series=none')).body.tip.height;
    const block = await client.get(`/api/block?height=${tip}`);
    const one = block.body.txids[3] ?? block.body.txids[0];
    const r = await client.get(`/api/tx?txid=${one}&block=${block.body.header.hash}`);
    assert.equal(r.status, 200);
    assert.equal(r.body.ok, true, JSON.stringify(r.body));
    assert.equal(r.body.txid, one);
    assert.ok(r.body.inputs.length >= 1 && r.body.outputs.length >= 1);
    assert.ok(r.body.confirmations >= 1);
    assert.ok(r.body.totalOutSat > 0, 'outputs summed in satoshis, not floats');
    assert.ok(r.body.notReported.some((n) => /fee/i.test(n)),
      'the fee is absent and says why: computing it needs every input\'s prevout, on a one-threaded RPC server');

    const badTx = await client.get('/api/tx?txid=abc');
    assert.equal(badTx.status, 400);
    const missing = await client.get(`/api/tx?txid=${'11'.repeat(32)}`);
    assert.equal(missing.body.ok, false);
    assert.match(missing.body.error.message, /not found/i);
    assert.match(missing.body.hint ?? '', /block/, 'the hint says what to add when a tx has left the pool');
  });
});

test('two nodes are both monitored, named, and kept apart', async () => {
  await withApp({ nodes: 2 }, async ({ client, app }) => {
    await client.login('admin');
    const nodes = await client.get('/api/nodes');
    assert.equal(nodes.body.nodes.length, 2, 'both configured nodes are live');
    const ids = nodes.body.nodes.map((n) => n.id).sort();
    assert.deepEqual(ids, ['node-1', 'node-a']);

    // Every node answers for itself. The measured failure this guards: one `peers`
    // ring holding 2,308 production rows and 1,816 bench rows, drawn as one line.
    const a = await client.get('/api/state?node=node-a&series=none');
    const b = await client.get('/api/state?node=node-1&series=none');
    assert.equal(a.body.id, 'node-a');
    assert.equal(b.body.id, 'node-1');
    assert.equal(a.body.sync.node, 'node-a', 'the sync bar carries its node inside it');
    assert.equal(b.body.sync.node, 'node-1');
    assert.notEqual(a.body.label, b.body.label, 'and says which one it is on screen');

    // Optional nodes degrade to a note, not a red app. node-1 is marked optional in
    // the test config; both are up here, so `ok` must be true either way.
    const health = await client.get('/api/health');
    assert.equal(health.body.ok, true);
    assert.deepEqual(health.body.degraded, []);

    // An unknown node on the stream is refused rather than streaming silence.
    const stream = await client.raw('/api/stream?node=who');
    assert.equal(stream.status, 404);
    assert.equal((await stream.json()).error.kind, 'unknown_node');

    assert.equal(app.monitors.size, 2);
  });
});

