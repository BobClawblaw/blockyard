test('the audit endpoint reports the size of the trail it is reading', async () => {
  await withApp({}, async ({ client }) => {
    await client.login('admin');
    await client.get('/api/health');
    const r = await client.get('/api/audit?limit=5');
    assert.equal(r.status, 200);
    const log = r.body.log;
    assert.ok(log.maxBytes >= 65536);
    assert.ok(log.currentBytes > 0, 'entries were written during this boot, so the file is not empty');
    assert.ok(log.headroomBytes <= log.maxBytes);
    assert.equal(log.rotationError, null, 'nothing failed to rotate in a test this short');
  });
});

