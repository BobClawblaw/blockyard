// mulberry32: 32 good bits per draw. (blockpack.test.js's LCG is fine for sizes, but its low bits are
// weak, and these generators build u32 fields and random bytes out of the draws.)
function rng(seed) {
  let a = seed >>> 0;
  const next = () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const r = () => next();
  r.int = (lo, hi) => lo + Math.floor(next() * (hi - lo + 1));          // inclusive
  r.u32 = () => Math.floor(next() * 4294967296) >>> 0;
  r.u64 = () => (BigInt(r.u32()) << 32n) | BigInt(r.u32());
  r.bytes = (n) => { const b = Buffer.alloc(n); for (let i = 0; i < n; i++) b[i] = Math.floor(next() * 256); return b; };
  r.pick = (xs) => xs[Math.floor(next() * xs.length)];
  return r;
}

const sha256 = (b) => createHash('sha256').update(b).digest();
const dsha = (b) => sha256(sha256(b));
const revHex = (b) => Buffer.from(b).reverse().toString('hex');
const MAX_SAFE = BigInt(Number.MAX_SAFE_INTEGER);

// a synchronous decoder cannot be interrupted, so "never hang" is measured instead: every case is
// timed and the slowest one is held under a budget far above a linear decode of these sizes
const CASE_BUDGET_MS = 250;
function timed(fn) {
  const t0 = performance.now();
  let value, error, threw = false;
  try { value = fn(); } catch (e) { threw = true; error = e; }
  return { value, error, threw, ms: performance.now() - t0 };
}

// --- the wire format, written from the spec ------------------------------
// CompactSize: < 0xfd is one byte; 0xfd + u16; 0xfe + u32; 0xff + u64
function compactSize(n) {
  n = BigInt(n);
  if (n < 0xfdn) return Buffer.from([Number(n)]);
  if (n <= 0xffffn) { const b = Buffer.alloc(3); b[0] = 0xfd; b.writeUInt16LE(Number(n), 1); return b; }
  if (n <= 0xffffffffn) { const b = Buffer.alloc(5); b[0] = 0xfe; b.writeUInt32LE(Number(n), 1); return b; }
  const b = Buffer.alloc(9); b[0] = 0xff; b.writeBigUInt64LE(n, 1); return b;
}
const pushBytes = (b) => Buffer.concat([compactSize(b.length), b]);
const u32le = (v) => { const b = Buffer.alloc(4); b.writeUInt32LE(v >>> 0); return b; };
const i32le = (v) => { const b = Buffer.alloc(4); b.writeInt32LE(v | 0); return b; };
const u64le = (v) => { const b = Buffer.alloc(8); b.writeBigUInt64LE(BigInt(v)); return b; };

// a transaction as the generator holds it: { version, vin: [{ prev, vout, script, sequence, witness }],
// vout: [{ value, script }], locktime }. BIP144: with a witness, version | 00 01 | ins | outs |
// witness per input | locktime; without, version | ins | outs | locktime.
function serializeTx(tx, withWitness) {
  const parts = [i32le(tx.version)];
  if (withWitness) parts.push(Buffer.from([0x00, 0x01]));
  parts.push(compactSize(tx.vin.length));
  for (const i of tx.vin) parts.push(i.prev, u32le(i.vout), pushBytes(i.script), u32le(i.sequence));
  parts.push(compactSize(tx.vout.length));
  for (const o of tx.vout) parts.push(u64le(o.value), pushBytes(o.script));
  if (withWitness) for (const i of tx.vin) { parts.push(compactSize(i.witness.length)); for (const w of i.witness) parts.push(pushBytes(w)); }
  parts.push(u32le(tx.locktime));
  return Buffer.concat(parts);
}
const hasWitness = (tx) => tx.vin.some((i) => i.witness.length > 0);

// script lengths that sit on the CompactSize boundaries, plus ordinary ones
function scriptLen(r) {
  const p = r();
  if (p < 0.03) return r.pick([0xfc, 0xfd, 0xfe, 0xff, 0x100]);
  if (p < 0.035) return r.pick([0xffff, 0x10000]);
  if (p < 0.15) return 0;
  return r.int(1, 120);
}
function randomScript(r) {
  const p = r();
  const h20 = () => r.bytes(20), h32 = () => r.bytes(32);
  if (p < 0.1) return Buffer.concat([Buffer.from([0x76, 0xa9, 0x14]), h20(), Buffer.from([0x88, 0xac])]);   // p2pkh
  if (p < 0.2) return Buffer.concat([Buffer.from([0xa9, 0x14]), h20(), Buffer.from([0x87])]);                // p2sh
  if (p < 0.3) return Buffer.concat([Buffer.from([0x00, 0x14]), h20()]);                                     // p2wpkh
  if (p < 0.4) return Buffer.concat([Buffer.from([0x51, 0x20]), h32()]);                                     // taproot
  if (p < 0.45) return Buffer.concat([Buffer.from([0x6a]), pushBytes(r.bytes(r.int(0, 40)))]);             // OP_RETURN-ish
  return r.bytes(scriptLen(r));
}
function randomAmount(r) {
  const p = r();
  if (p < 0.1) return BigInt(r.pick([0, 1, 546, 2_100_000_000_000_000, Number.MAX_SAFE_INTEGER]));
  return BigInt(r.int(0, 2_100_000_000_000_000));
}
function randomTx(r, { segwit }) {
  // A LEGACY TRANSACTION NEEDS AT LEAST ONE INPUT: with none, its bytes begin version | 00 | ... and a
  // following output count of 1 reads as the BIP144 marker and flag. Core resolves that the same way
  // (it tries witness first), and a transaction with no inputs is invalid anyway.
  const nin = r() < 0.05 ? r.int(0xfd, 0x100) : r.int(1, 6);
  const nout = r() < 0.05 ? 0 : r() < 0.03 ? r.int(0xfd, 0x100) : r.int(1, 6);
  const vin = [];
  for (let i = 0; i < nin; i++) {
    const coinbase = i === 0 && r() < 0.1;
    const witness = [];
    if (segwit && r() < 0.8) {
      const items = r() < 0.02 ? 0xfd : r.int(1, 5);
      for (let k = 0; k < items; k++) witness.push(r() < 0.15 ? Buffer.alloc(0) : r.bytes(r() < 0.02 ? 0xfd : r.int(1, 80)));
    }
    vin.push({
      prev: coinbase ? Buffer.alloc(32) : r.bytes(32),
      vout: coinbase ? 0xffffffff : r.pick([0, 1, 2, 0xffffffff, r.u32()]),
      script: randomScript(r),
      sequence: r.pick([0xffffffff, 0xfffffffe, 0xfffffffd, 0, r.u32()]),
      witness,
    });
  }
  // BIP144 FORBIDS A WITNESS SERIALIZATION WITH NO WITNESS IN IT (Core: "Superfluous witness record"),
  // so a segwit transaction always carries at least one non-empty stack
  if (segwit && !hasWitness({ vin })) vin[r.int(0, nin - 1)].witness.push(r.bytes(r.int(0, 72)));
  const vout = Array.from({ length: nout }, () => ({ value: randomAmount(r), script: randomScript(r) }));
  return { version: r.pick([1, 2, 3, -1, 0x7fffffff, r.u32() | 0]), vin, vout, locktime: r.pick([0, 499_999_999, 500_000_000, r.u32()]) };
}

// The decoded shape back into the generator's form, so a decode can be re-serialized. Whether the
// decode was a witness serialization is read off weight: a legacy one weighs exactly size * 4.
function fromDecoded(d) {
  return {
    segwit: d.weight !== d.size * 4,
    tx: {
      version: d.version,
      vin: d.vin.map((i) => ({
        prev: i.coinbase != null ? Buffer.alloc(32) : Buffer.from(i.txid, 'hex').reverse(),
        vout: i.coinbase != null ? 0xffffffff : i.vout,
        script: Buffer.from(i.coinbase ?? i.scriptSig.hex, 'hex'),
        sequence: i.sequence,
        witness: (i.txinwitness ?? []).map((w) => Buffer.from(w, 'hex')),
      })),
      vout: d.vout.map((o) => ({ value: BigInt(o.value_sat), script: Buffer.from(o.scriptPubKey.hex, 'hex') })),
      locktime: d.locktime,
    },
  };
}

function assertDecodesAs(d, tx, segwit, at) {
  const base = serializeTx(tx, false), full = segwit ? serializeTx(tx, true) : base;
  assert.equal(d.txid, revHex(dsha(base)), `${at}: txid is double-SHA256 of the serialization WITHOUT witness`);
  assert.equal(d.hash, revHex(dsha(full)), `${at}: hash (wtxid) is double-SHA256 of the full serialization`);
  assert.equal(d.size, full.length, `${at}: size`);
  assert.equal(d.weight, base.length * 3 + full.length, `${at}: weight is base * 3 + total`);
  assert.equal(d.vsize, Math.ceil(d.weight / 4), `${at}: vsize`);
  assert.equal(d.version, tx.version, `${at}: version`);
  assert.equal(d.locktime, tx.locktime, `${at}: locktime`);
  assert.equal(d.vin.length, tx.vin.length, `${at}: input count`);
  tx.vin.forEach((w, i) => {
    const g = d.vin[i];
    const coinbase = w.vout === 0xffffffff && w.prev.every((b) => b === 0);
    if (coinbase) assert.equal(g.coinbase, w.script.toString('hex'), `${at}: vin ${i} coinbase script`);
    else {
      assert.equal(g.txid, revHex(w.prev), `${at}: vin ${i} txid is the outpoint hash, reversed`);
      assert.equal(g.vout, w.vout, `${at}: vin ${i} vout`);
      assert.equal(g.scriptSig.hex, w.script.toString('hex'), `${at}: vin ${i} scriptSig`);
    }
    assert.equal(g.sequence, w.sequence, `${at}: vin ${i} sequence`);
    // Core omits txinwitness for an empty stack; an empty ITEM inside a stack is still an item
    assert.deepEqual(g.txinwitness ?? [], w.witness.map((b) => b.toString('hex')), `${at}: vin ${i} witness`);
    if (!w.witness.length) assert.equal(g.txinwitness, undefined, `${at}: vin ${i} has no txinwitness key when the stack is empty`);
  });
  assert.equal(d.vout.length, tx.vout.length, `${at}: output count`);
  tx.vout.forEach((w, n) => {
    const g = d.vout[n];
    assert.equal(g.n, n, `${at}: vout ${n} index`);
    assert.equal(BigInt(g.value_sat), w.value, `${at}: vout ${n} value, to the satoshi`);
    assert.ok(Number.isSafeInteger(g.value_sat), `${at}: vout ${n} value is an exact integer`);
    assert.equal(g.scriptPubKey.hex, w.script.toString('hex'), `${at}: vout ${n} script`);
    const c = classifyScript(w.script);
    assert.equal(g.scriptPubKey.type, c.type, `${at}: vout ${n} type`);
    assert.equal(g.scriptPubKey.address, c.address ?? undefined, `${at}: vout ${n} address`);
  });
}

