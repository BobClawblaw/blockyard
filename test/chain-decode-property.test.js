test('blk/rev files: XOR is its own inverse at any offset, and framing a file cut anywhere yields exactly its whole records', () => {
  const r = rng(0xf11e);
  const nets = Object.values(MAGIC);
  for (let c = 0; c < 200; c++) {
    const key = r() < 0.2 ? Buffer.alloc(8) : r.bytes(8);
    const magic = r.pick(nets), trailer = r() < 0.5 ? 32 : 0;
    const bodies = Array.from({ length: r.int(0, 5) }, () => r.bytes(r.int(1, 300)));
    const frames = bodies.map((b) => { const h = Buffer.alloc(8); h.writeUInt32LE(magic, 0); h.writeUInt32LE(b.length, 4); return Buffer.concat([h, b, r.bytes(trailer)]); });
    const plain = Buffer.concat([...frames, r() < 0.5 ? Buffer.alloc(r.int(0, 64)) : Buffer.alloc(0)]);
    const disk = unxor(Buffer.from(plain), key, 0);
    // XOR by absolute offset: de-obfuscating any slice on its own agrees with the whole file
    const off = r.int(0, plain.length), len = r.int(0, plain.length - off);
    assert.ok(unxor(Buffer.from(disk.subarray(off, off + len)), key, off).equals(plain.subarray(off, off + len)), `case ${c}: a slice at ${off} unxors on its own`);
    assert.ok(unxor(unxor(Buffer.from(plain), key, 7), key, 7).equals(plain), `case ${c}: unxor twice is the identity`);
    // cut the file anywhere, as the last file is while Core appends: only whole records come out
    const ends = []; let pos = 0;
    for (const f of frames) { pos += f.length; ends.push(pos); }
    for (let cut = 0; cut <= plain.length; cut += r.int(1, 17)) {
      const got = [...records(plain.subarray(0, cut), magic, trailer)];
      const whole = ends.filter((e) => e <= cut).length;
      assert.equal(got.length, whole, `case ${c}: a file cut at ${cut} holds ${whole} whole records`);
      got.forEach((g, i) => assert.ok(g.body.equals(bodies[i]), `case ${c}: record ${i} body`));
    }
  }
});
