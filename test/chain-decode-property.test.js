test('CompactSize: every boundary and 20,000 random values read back exactly, consuming exactly their encoding', () => {
  const r = rng(0xc0a1);
  const edges = [0n, 1n, 0xfcn, 0xfdn, 0xfen, 0xffn, 0x100n, 0xfffen, 0xffffn, 0x10000n, 0xfffffffen, 0xffffffffn, 0x100000000n, MAX_SAFE - 1n, MAX_SAFE];
  const values = [...edges];
  for (let i = 0; i < 20_000; i++) {
    const bits = r.int(0, 53);
    values.push(BigInt(Math.floor(r() * 2 ** bits)));
  }
  const width = (n) => (n < 0xfdn ? 1 : n <= 0xffffn ? 3 : n <= 0xffffffffn ? 5 : 9);
  for (const n of values) {
    const enc = compactSize(n);
    assert.equal(enc.length, width(n), `${n} encodes in ${width(n)} bytes`);
    const rd = new Reader(Buffer.concat([enc, Buffer.from([0xaa])]));
    assert.equal(rd.varint(), Number(n), `${n} reads back`);
    assert.equal(rd.pos, enc.length, `${n}: the reader stops right after the encoding`);
  }
  assert.equal(compactSize(0xfc)[0], 0xfc, '0xfc is still one byte');
  assert.deepEqual([...compactSize(0xfd)], [0xfd, 0xfd, 0x00], '0xfd itself needs the u16 form');
  // past 2^53 a JavaScript number cannot hold it: an error, never a rounded count
  for (const n of [MAX_SAFE + 1n, 0xffffffffffffffffn, r.u64() | (1n << 63n)]) {
    assert.throws(() => new Reader(compactSize(n)).varint(), RangeError, `${n} is refused, not rounded`);
  }
  // truncated at every byte of every width: an error, never a short read
  for (const n of [0xfdn, 0x10000n, 0x100000000n]) {
    const enc = compactSize(n);
    for (let cut = 0; cut < enc.length; cut++) assert.throws(() => new Reader(enc.subarray(0, cut)).varint(), RangeError, `${n} cut at ${cut}`);
  }
});

// --- Core's VARINT and CompressAmount, in the undo data ----------------------
// serialize.h WriteVarInt, in BigInt so the oracle is exact across all of uint64
function varInt(n) {
  n = BigInt(n);
  const tmp = [];
  for (let len = 0; ; len++) {
    tmp.push(Number((n & 0x7fn) | (len ? 0x80n : 0n)));
    if (n <= 0x7fn) break;
    n = (n >> 7n) - 1n;
  }
  return Buffer.from(tmp.reverse());
}
// compressor.cpp CompressAmount / DecompressAmount, in BigInt
function compressAmount(n) {
  n = BigInt(n);
  if (n === 0n) return 0n;
  let e = 0n;
  while (n % 10n === 0n && e < 9n) { n /= 10n; e++; }
  if (e < 9n) { const d = n % 10n; n /= 10n; return 1n + (n * 9n + d - 1n) * 10n + e; }
  return 1n + (n - 1n) * 10n + 9n;
}
function decompressAmountBig(x) {
  if (x === 0n) return 0n;
  x -= 1n;
  let e = x % 10n; x /= 10n;
  let n;
  if (e < 9n) { const d = (x % 9n) + 1n; x /= 9n; n = x * 10n + d; } else n = x + 1n;
  while (e > 0n) { n *= 10n; e--; }
  return n;
}

test('VARINT: the oracle writes serialize_tests.cpp\'s own vectors', () => {
  // (so the round trips below are against Core's encoding, not against a second copy of a mistake)
  for (const [n, hex] of [[0n, '00'], [0x7fn, '7f'], [0x80n, '8000'], [0x1234n, 'a334'], [0xffffn, '82fe7f'], [0x123456n, 'c7e756'],
    [0x80123456n, '86ffc7e756'], [0xffffffffn, '8efefefe7f'], [0x7fffffffffffffffn, 'fefefefefefefefe7f'], [0xffffffffffffffffn, '80fefefefefefefefe7f']]) {
    assert.equal(varInt(n).toString('hex'), hex, `VARINT(${n.toString(16)})`);
  }
  for (const [amount, c] of [[0n, 0n], [1n, 1n], [1_000_000n, 7n], [100_000_000n, 9n], [5_000_000_000n, 0x32n], [2_100_000_000_000_000n, 0x1406f40n]]) {
    assert.equal(compressAmount(amount), c, `CompressAmount(${amount})`);
    assert.equal(decompressAmountBig(c), amount);
  }
});

// one coin as Core's undo writer lays it out (undo.h TxInUndoFormatter): VARINT(height*2 + coinbase),
// a VARINT(0) version placeholder when height > 0, VARINT(CompressAmount(value)), then the script as
// VARINT(template or size + 6) and its bytes
function coinBytes({ height, coinbase, amountVarInt, scriptBytes }) {
  return Buffer.concat([varInt(BigInt(height) * 2n + (coinbase ? 1n : 0n)), ...(height > 0 ? [varInt(0)] : []), varInt(amountVarInt), scriptBytes]);
}
const rawScript = (s) => Buffer.concat([varInt(s.length + 6), s]);

test('CompressAmount: 50,000 amounts across 0..21e14 satoshis, and every edge, come back exact through the undo decoder', () => {
  const r = rng(0xa11);
  const amounts = [0n, 1n, 9n, 10n, 11n, 99n, 100n, 546n, 100_000_000n, 5_000_000_000n, 999_999_999_999_999n, 1_000_000_000_000_000n,
    1_000_000_000_000_001n, 2_099_999_999_999_999n, 2_100_000_000_000_000n, 2_099_999_999_999_990n, 1_234_567_890_123_457n, 1_999_999_999n];
  for (let i = 0; i < 50_000; i++) {
    const p = r();
    // plain uniform draws almost never end in zeros, and trailing zeros are what the exponent codes
    let a = p < 0.5 ? BigInt(r.int(0, 2_100_000_000_000_000)) : BigInt(r.int(0, 2_100_000)) * 10n ** BigInt(r.int(0, 9));
    if (a > 2_100_000_000_000_000n) a = 2_100_000_000_000_000n;
    amounts.push(a);
  }
  // the whole batch as one undo record, one coin per transaction, so the decoder reads 50,000 VARINTs
  const body = Buffer.concat([compactSize(amounts.length), ...amounts.map((a, i) => Buffer.concat([
    compactSize(1), coinBytes({ height: i, coinbase: false, amountVarInt: compressAmount(a), scriptBytes: rawScript(Buffer.from([0x51])) }),
  ]))]);
  const t0 = performance.now();
  const undo = decodeBlockUndo(body);
  const ms = performance.now() - t0;
  amounts.forEach((a, i) => {
    assert.equal(decompressAmountBig(compressAmount(a)), a, `the oracle round-trips ${a}`);
    assert.equal(undo[i][0].value_sat, Number(a), `amount ${a} (compressed ${compressAmount(a)}) decodes to the satoshi`);
    assert.equal(undo[i][0].height, i);
  });
  // THE BUG THIS FOUND: a compressed amount is about 9x the amount when it does not end in a zero, so
  // anything from ~1e15 satoshis up (10M BTC in one output, in range, if never seen) compresses past
  // 2^53, where Number arithmetic in readVarInt and decompressAmount rounds it. 2,099,999,999,999,999
  // came back as 209,999,999,999,999,940 before the fix: the rounding moved the exponent digit.
  assert.equal(decodeBlockUndo(Buffer.from('01010200a0c8adb1d183fe770751', 'hex'))[0][0].value_sat, 2_099_999_999_999_999,
    'regression: the exact undo bytes that decoded a hundred times too large');
  const worst = 2_099_999_999_999_999n;
  assert.ok(compressAmount(worst) > MAX_SAFE, 'the edge case really does compress past 2^53');
  assert.equal(decompressAmount(compressAmount(worst)), Number(worst), 'decompressAmount takes a BigInt and is exact past 2^53');
  assert.ok(ms < 2000, `50,000 coins decode in ${ms.toFixed(0)} ms`);
});

test('VARINT: 20,000 random uint64 amount fields decode exactly, or are refused when the value cannot be an exact number', () => {
  const r = rng(0x7a1);
  let exact = 0, refused = 0;
  const fields = [0n, 0x7fn, 0x80n, MAX_SAFE, MAX_SAFE + 1n, 0xffffffffffffffffn];
  for (let i = 0; i < 20_000; i++) fields.push(r.u64() >> BigInt(r.int(0, 63)));
  for (const x of fields) {
    const body = Buffer.concat([compactSize(1), compactSize(1), coinBytes({ height: 1, coinbase: true, amountVarInt: x, scriptBytes: rawScript(Buffer.alloc(0)) })]);
    const want = decompressAmountBig(x);
    const got = timed(() => decodeBlockUndo(body));
    if (want <= MAX_SAFE) {
      assert.equal(got.threw, false, `field ${x}: decodes (${got.error?.message})`);
      assert.equal(got.value[0][0].value_sat, Number(want), `field ${x} decompresses to ${want}`);
      exact++;
    } else {
      assert.ok(got.error instanceof RangeError, `field ${x} decompresses to ${want}, past 2^53: refused with a RangeError, not rounded`);
      refused++;
    }
  }
  assert.ok(exact > 1000 && refused > 1000, `both sides exercised (${exact} exact, ${refused} refused)`);
  // a VARINT wider than uint64 is corrupt (Core: "ReadVarInt(): size too large")
  const tooWide = Buffer.concat([compactSize(1), compactSize(1), varInt(3), varInt(0), Buffer.from('80fefefefefefefefeff00', 'hex'), rawScript(Buffer.alloc(0))]);
  assert.throws(() => decodeBlockUndo(tooWide), RangeError, 'past uint64');
  // the height code is uint32 in Core: a run of continuation bytes there used to decode as a height
  // of 7.6e22 -- the same unbounded read the undo byte-flip property caught as a value past 2^53
  assert.throws(() => decodeBlockUndo(Buffer.from('0101ffffffffffffffffffff0000090651', 'hex')), /VARINT too large/, 'a height code past uint32');
});

// secp256k1, for generating keys the compressed P2PK templates (4, 5) can carry
const P = 0xfffffffffffffffffffffffffffffffffffffffffffffffffffffffefffffc2fn;
function modpow(b, e, m) { let x = 1n; b %= m; while (e > 0n) { if (e & 1n) x = (x * b) % m; b = (b * b) % m; e >>= 1n; } return x; }
function randomCurvePoint(r) {
  for (;;) {
    const x = BigInt('0x' + r.bytes(32).toString('hex')) % P;
    const rhs = (x ** 3n + 7n) % P;
    const y = modpow(rhs, (P + 1n) / 4n, P);
    if ((y * y) % P === rhs) return { x: Buffer.from(x.toString(16).padStart(64, '0'), 'hex'), y: Buffer.from((r() < 0.5 ? y : P - y).toString(16).padStart(64, '0'), 'hex') };
  }
}

// a random undo record: { body, want: [[{ height, coinbase, value_sat, script }]] }
function randomUndo(r) {
  const ntx = r() < 0.1 ? 0 : r.int(1, 6);
  const want = [], parts = [compactSize(ntx)];
  for (let t = 0; t < ntx; t++) {
    const nin = r.int(r() < 0.1 ? 0 : 1, 5);
    parts.push(compactSize(nin));
    const coins = [];
    for (let j = 0; j < nin; j++) {
      const height = r.pick([0, 1, 0x7f, 0x80, 900_000, 0x7fffffff, r.int(0, 1_000_000)]);
      const coinbase = r() < 0.2;
      const value = randomAmount(r);
      const kind = r.int(0, 6);
      let script, stored;
      if (kind === 0) { const h = r.bytes(20); script = Buffer.concat([Buffer.from([0x76, 0xa9, 0x14]), h, Buffer.from([0x88, 0xac])]); stored = Buffer.concat([varInt(0), h]); }
      else if (kind === 1) { const h = r.bytes(20); script = Buffer.concat([Buffer.from([0xa9, 0x14]), h, Buffer.from([0x87])]); stored = Buffer.concat([varInt(1), h]); }
      else if (kind === 2) { const k = 2 + r.int(0, 1), x = r.bytes(32); script = Buffer.concat([Buffer.from([0x21, k]), x, Buffer.from([0xac])]); stored = Buffer.concat([varInt(k), x]); }
      else if (kind === 3) {
        const { x, y } = randomCurvePoint(r);
        script = Buffer.concat([Buffer.from([0x41, 0x04]), x, y, Buffer.from([0xac])]);
        stored = Buffer.concat([varInt(4 + (y[31] & 1)), x]);
      } else { script = r.bytes(scriptLen(r)); stored = rawScript(script); }
      parts.push(coinBytes({ height, coinbase, amountVarInt: compressAmount(value), scriptBytes: stored }));
      coins.push({ height, coinbase, value_sat: Number(value), script });
    }
    want.push(coins);
  }
  return { body: Buffer.concat(parts), want };
}

