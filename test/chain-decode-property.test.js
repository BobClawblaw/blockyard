test('undo records: truncated at every byte offset, both readers throw an Error -- never a shorter record', () => {
  // THE BUG THIS FOUND: undoShape skips script bytes by moving its position and never looked at where
  // it ended, so a record cut in the middle of a script returned the full input counts, as if whole.
  // It is what pairs undo records with blocks, so a half-written rev file could shape-match. And
  // decodeBlockUndo's take() sliced past the end silently, only failing later with "-N bytes left".
  const r = rng(0x7c);
  let cuts = 0, slowest = 0;
  for (let c = 0; c < 80; c++) {
    const { body } = randomUndo(r);
    if (body.length > 2000) { c--; continue; }          // a 64 KB script makes the every-offset sweep quadratic
    for (let cut = 0; cut < body.length; cut++) {
      const part = body.subarray(0, cut);
      for (const [name, fn] of [['decodeBlockUndo', decodeBlockUndo], ['undoShape', undoShape]]) {
        const got = timed(() => fn(part));
        slowest = Math.max(slowest, got.ms);
        assert.ok(got.threw, `case ${c}: ${name} on the first ${cut} of ${body.length} bytes must throw (returned ${JSON.stringify(got.value)?.slice(0, 80)})`);
        assert.ok(got.error instanceof Error, `case ${c}: ${name} cut at ${cut} throws an Error, not ${String(got.error)}`);
      }
      cuts++;
    }
  }
  assert.ok(slowest < CASE_BUDGET_MS, `every truncation answered promptly (slowest ${slowest.toFixed(1)} ms over ${cuts} cuts)`);
  // regression: one coin with a 10-byte raw script, cut 3 bytes short. undoShape returned [1].
  const cutShort = Buffer.from('01010200091000000000000000', 'hex');
  assert.throws(() => undoShape(cutShort), /truncated undo record/, 'undoShape refuses a record cut inside its last script');
  assert.throws(() => decodeBlockUndo(cutShort), /truncated script/, 'and decodeBlockUndo says where, not "-3 bytes left"');
});

test('undo records: random byte flips either throw an Error or decode to well-formed coins both readers agree on', () => {
  const r = rng(0xf11b);
  let threw = 0, decoded = 0, slowest = 0;
  for (let c = 0; c < 5000; c++) {
    const { body } = randomUndo(r);
    if (!body.length) continue;
    const bad = Buffer.from(body);
    for (let k = r.int(1, 3); k > 0; k--) bad[r.int(0, bad.length - 1)] ^= r.int(1, 255);
    const full = timed(() => decodeBlockUndo(bad)), shape = timed(() => undoShape(bad));
    slowest = Math.max(slowest, full.ms, shape.ms);
    for (const g of [full, shape]) if (g.threw) assert.ok(g.error instanceof Error, `case ${c}: throws an Error, not ${String(g.error)}`);
    if (full.threw) { threw++; continue; }
    decoded++;
    assert.equal(shape.threw, false, `case ${c}: decodeBlockUndo accepted it, so undoShape must too (${shape.error?.message})`);
    assert.deepEqual(shape.value, full.value.map((t) => t.length), `case ${c}: and they agree on its shape`);
    for (const coin of full.value.flat()) {
      assert.ok(Number.isSafeInteger(coin.height) && coin.height >= 0, `case ${c}: height ${coin.height} is an exact integer`);
      assert.ok(Number.isSafeInteger(coin.value_sat) && coin.value_sat >= 0, `case ${c}: value ${coin.value_sat} is an exact integer`);
      assert.ok(Buffer.isBuffer(coin.script), `case ${c}: script is bytes`);
    }
  }
  assert.ok(threw > 500 && decoded > 50, `both outcomes exercised (${threw} threw, ${decoded} decoded)`);
  assert.ok(slowest < CASE_BUDGET_MS, `slowest case ${slowest.toFixed(1)} ms`);
});

