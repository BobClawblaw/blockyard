    const header = Buffer.concat([i32le(r.u32() | 0), r.bytes(32), r.bytes(32), u32le(r.u32()), u32le(r.u32()), u32le(r.u32())]);
    const txs = Array.from({ length: r() < 0.02 ? 0xfd : r.int(1, 8) }, () => { const segwit = r() < 0.5; return { segwit, tx: randomTx(r, { segwit }) }; });
