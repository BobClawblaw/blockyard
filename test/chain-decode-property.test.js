// PROPERTIES OF THE CHAIN DECODERS (server/chain/tx.js, server/chain/blockfile.js), over thousands of
// generated inputs rather than a handful of fixtures.
//
// Why this file exists next to chain-tx.test.js and chain-blockfile.test.js: those check the decoders
// against what Core said about REAL bytes, which is the strongest evidence for the bytes Core has
// actually produced -- and says nothing about the corners the chain has not visited yet (a script of
// exactly 0xfd bytes, an amount past 2^53 once compressed, a witness item of zero length in the
// middle of a stack) or about what the decoder does with bytes that are wrong. The address index is
// built from files on disk that can be half-written or damaged, so "throws a clear Error" versus
// "returns something plausible" is a real difference there.
//
// Everything here is generated by a small seeded PRNG written below (no libraries, Rule 1), so a
// failure prints its seed and case number and reproduces exactly. The oracles are written from the
// wire format and from Core's serialize.h / compressor.cpp, in BigInt where Core uses uint64, and are
// deliberately NOT the decoder's own helpers -- a property that checks a function against itself
// proves nothing.
