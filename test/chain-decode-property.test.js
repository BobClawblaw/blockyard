test('transactions: random byte flips either throw an Error or decode to a transaction that re-serializes to exactly those bytes', () => {
  // "re-serializes to exactly those bytes" is the strong form of "no partial object": every byte was
  // read, into the field it belongs to, and nothing was skipped, rounded or guessed
  const r = rng(0xf1f);
  let threw = 0, decoded = 0, slowest = 0;
  const reasons = new Map();
  for (let c = 0; c < 20_000; c++) {
    const segwit = r() < 0.5;
    const tx = randomTx(r, { segwit });
    const bytes = serializeTx(tx, segwit);
    if (bytes.length > 3000) continue;
    const bad = Buffer.from(bytes);
    // bias toward the structural bytes at the front, where a flip changes how the rest is framed
    for (let k = r.int(1, 3); k > 0; k--) bad[r() < 0.5 ? r.int(0, Math.min(bad.length - 1, 60)) : r.int(0, bad.length - 1)] ^= r() < 0.3 ? 1 << r.int(0, 7) : r.int(1, 255);
    const got = timed(() => decodeTx(bad));
    slowest = Math.max(slowest, got.ms);
    if (got.threw) {
      assert.ok(got.error instanceof Error, `case ${c}: an Error, not ${String(got.error)}`);
      const why = got.error.message.replace(/[0-9]+/g, 'N');
      reasons.set(why, (reasons.get(why) ?? 0) + 1);
      threw++;
      continue;
    }
    decoded++;
    const back = fromDecoded(got.value);
    assert.ok(serializeTx(back.tx, back.segwit).equals(bad), `case ${c}: decoded bytes ${bad.toString('hex').slice(0, 80)}... re-serialize identically`);
    assert.equal(got.value.hash, revHex(dsha(bad)), `case ${c}: the wtxid is of the bytes given`);
  }
  assert.ok(threw > 1000 && decoded > 1000, `both outcomes exercised (${threw} threw, ${decoded} decoded)`);
  assert.ok(slowest < CASE_BUDGET_MS, `slowest ${slowest.toFixed(1)} ms`);
});

